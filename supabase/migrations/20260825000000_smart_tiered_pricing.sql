-- 1. Create Category Prices Table
CREATE TABLE public.category_prices (
    category TEXT PRIMARY KEY,
    base_cost NUMERIC DEFAULT 0,
    base_price NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.category_prices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable read access for all users" ON public.category_prices FOR SELECT USING (true);
CREATE POLICY "Enable write access for authenticated users" ON public.category_prices FOR ALL USING (auth.role() = 'authenticated');

-- 2. Create Pricing Rules Table
CREATE TABLE public.pricing_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT REFERENCES public.category_prices(category) ON DELETE CASCADE,
    condition_attribute TEXT NOT NULL,
    condition_value TEXT NOT NULL,
    modifier_amount NUMERIC NOT NULL,
    modifier_type TEXT DEFAULT 'fixed_addition',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.pricing_rules ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable read access for all users" ON public.pricing_rules FOR SELECT USING (true);
CREATE POLICY "Enable write access for authenticated users" ON public.pricing_rules FOR ALL USING (auth.role() = 'authenticated');

-- 3. Update Product Variants Table with Overrides
ALTER TABLE public.product_variants
ADD COLUMN cost_override NUMERIC DEFAULT NULL,
ADD COLUMN price_override NUMERIC DEFAULT NULL;

-- Trigger to update updated_at on category_prices
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_category_prices_modtime
BEFORE UPDATE ON public.category_prices
FOR EACH ROW
EXECUTE FUNCTION public.handle_updated_at();

CREATE TRIGGER update_pricing_rules_modtime
BEFORE UPDATE ON public.pricing_rules
FOR EACH ROW
EXECUTE FUNCTION public.handle_updated_at();
