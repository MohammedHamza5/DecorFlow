-- 1. Purchase Orders
CREATE TABLE public.purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT REFERENCES public.suppliers(id) ON DELETE CASCADE,
    invoice_number TEXT,
    total_amount NUMERIC DEFAULT 0,
    paid_amount NUMERIC DEFAULT 0,
    status TEXT DEFAULT 'pending',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE public.purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
    product_variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE CASCADE,
    quantity NUMERIC NOT NULL,
    unit_cost NUMERIC NOT NULL,
    total_cost NUMERIC NOT NULL
);

-- 2. Stock Movements (Inventory Ledger)
CREATE TABLE public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE CASCADE,
    movement_type TEXT NOT NULL, -- purchase_receive, sales_dispatch, sales_return, wastage, adjustment
    quantity_change NUMERIC NOT NULL, -- Positive for IN, Negative for OUT
    reference_id BIGINT, -- ID of PO, Invoice, Return
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Cash Transactions (Cash Flow Ledger)
CREATE TABLE public.cash_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC NOT NULL,
    type TEXT NOT NULL, -- 'in', 'out'
    category TEXT NOT NULL, -- 'customer_payment', 'supplier_payment', 'expense', 'refund', 'adjustment'
    reference_id BIGINT,
    payment_method TEXT DEFAULT 'cash',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Expenses
CREATE TABLE public.expense_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL
);

CREATE TABLE public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.expense_categories(id) ON DELETE SET NULL,
    amount NUMERIC NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

